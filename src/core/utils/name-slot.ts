// ============================================================
// 联盟杀 · 引擎文案里的「名字占位符」（欠账 D40）
//
// 引擎会拼整句：日志的「某某回复了 2 点体力」、濒死求桃的提问、
// 目标非法的拒绝原因。这些句子里都有**名字**，而换皮表在展示层，
// 引擎拿不到它——于是「关羽」换不成「德莱厄斯」，界面上一半是 LOL
// 名、一半是三国杀名。
//
// 现在的规矩：**引擎只记 ID，名字由展示层补**。句子里出现的是
// 占位符，展示层那张换皮表里的解析函数（全仓唯一出口）把它换成
// 人名 / 牌名。引擎这一侧连那张表的名字都不许出现——它一旦认识换皮，
// 规则就背上了一套皮肤。
//
// 占位符带 ID 而不是「第几个人」，是因为提问文案要穿过
// 「引擎 → 决策服务 → 弹窗」这条只传字符串的管道：带 ID 的占位符
// 自己就是完整信息，旁边不必再配一份结构化字段——那才是第二份答案。
//
// 两个函数收的都是**稳定 ID**（英雄 id / 卡牌定义 id），不是显示名——
// 显示名引擎没有，也不该有。
//
// 只留这两个：技能名在展示层由 `useSkill` 换（`ISkill → SkillUIInfo`
// 本来就换过一次），引擎那句「发动效果：xxx」是开发日志，够不着玩家，
// 因此这里没有技能的份——多一个零调用方的出口，就多一处不知道对错的答案。
// ============================================================

/** 角色 —— 传没有英雄的角色时，把座位 id 传进来（展示层查不到换皮就原样显示） */
export function heroSlot(id: string): string {
  return `{hero:${id}}`
}

/** 卡牌 —— 用**定义** id 而不是实例 id：换皮表按定义 id 索引 */
export function cardSlot(id: string): string {
  return `{card:${id}}`
}
